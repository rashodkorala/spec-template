"""Read device-tests/ cases and render the README index. Used by scripts/device-tests and scripts/check."""
import re
from dataclasses import dataclass, field
from pathlib import Path

from spec_config import DEVICE_PLATFORMS

ROOT = Path(__file__).resolve().parent.parent
DT_DIR = ROOT / "device-tests"
README = DT_DIR / "README.md"
PLATFORMS = tuple(DEVICE_PLATFORMS)
STATUSES = {"ready", "todo", "blocked", "deferred", "n/a", "retired"}
RESULTS = {"PASS", "FAIL"}
INDEX_START = "<!-- index:start (generated by scripts/device-tests; do not edit by hand) -->"
INDEX_END = "<!-- index:end -->"


@dataclass
class Case:
    path: Path
    feature: str
    cid: str = ""
    title: str = ""
    rules: str = ""
    status: dict[str, str] = field(default_factory=dict)  # platform -> status
    results: list[tuple[str, str, str]] = field(default_factory=list)  # (date, platform, result)

    def latest(self, platform: str) -> tuple[str, str] | None:
        runs = [(d, r) for d, p, r in self.results if p == platform]
        if not runs:
            return None
        best = max(d for d, _ in runs)
        return [run for run in runs if run[0] == best][-1]  # same day: the later row wins


def _cells(line: str) -> list[str]:
    return [c.strip() for c in line.strip().strip("|").split("|")]


def _table_after(lines: list[str], header_start: str) -> list[list[str]] | None:
    for i, line in enumerate(lines):
        if line.startswith(header_start):
            rows = []
            for row in lines[i + 2:]:
                if not row.startswith("|"):
                    break
                rows.append(_cells(row))
            return rows
    return None


def parse(path: Path, errors: list[str]) -> Case:
    rel = path.relative_to(ROOT)
    case = Case(path=path, feature=path.parent.name)
    text = path.read_text()
    lines = text.splitlines()
    m = re.match(r"^# (DT-[A-Z]+-\d{2}): (.+)$", lines[0] if lines else "")
    if not m:
        errors.append(f"{rel}: first line must be '# DT-<AREA>-<nn>: <title>'")
    else:
        case.cid, case.title = m.group(1), m.group(2).strip()
        if not path.name.startswith(case.cid + "-"):
            errors.append(f"{rel}: file name must start with '{case.cid}-'")
    rm = re.search(r"Rules:\s*([^\n(]+)", text)
    case.rules = rm.group(1).strip() if rm else ""

    platform_rows = _table_after(lines, "| Platform | Status |")
    if platform_rows is None:
        errors.append(f"{rel}: missing the '| Platform | Status | Build to test | Notes |' table")
    else:
        for row in platform_rows:
            platform, status = row[0], (row[1] if len(row) > 1 else "")
            if platform not in PLATFORMS:
                errors.append(f"{rel}: platform '{platform}' must be one of {', '.join(PLATFORMS)}")
            elif status not in STATUSES:
                errors.append(f"{rel}: {platform} status '{status}' must be one of {', '.join(sorted(STATUSES))}")
            else:
                case.status[platform] = status

    if "## Results" not in text:
        errors.append(f"{rel}: missing '## Results' section")
    result_rows = _table_after(lines, "| Date | Platform |") or []
    for row in result_rows:
        if len(row) < 7:
            errors.append(f"{rel}: Results row has too few columns: {' | '.join(row)}")
            continue
        date, platform, result = row[0], row[1], row[6]
        if not re.match(r"^\d{4}-\d{2}-\d{2}$", date):
            errors.append(f"{rel}: Results date '{date}' must be YYYY-MM-DD")
        if platform not in case.status:
            errors.append(f"{rel}: Results platform '{platform}' is not in the case's platform table")
        if result not in RESULTS:
            errors.append(f"{rel}: Results result '{result}' must be PASS or FAIL")
        case.results.append((date, platform, result))
    return case


def load(errors: list[str]) -> list[Case]:
    if not DT_DIR.exists():
        return []
    for stray in sorted(DT_DIR.glob("DT-*.md")):
        errors.append(f"{stray.relative_to(ROOT)}: cases live in a feature subfolder, e.g. device-tests/<feature>/")
    feature_names = {p.name for p in (ROOT / "features").iterdir() if p.is_dir() and p.name != "_template"}
    cases, seen = [], {}
    for path in sorted(DT_DIR.glob("*/DT-*.md")):
        if path.parent.name not in feature_names:
            errors.append(f"{path.relative_to(ROOT)}: folder '{path.parent.name}' is not a feature in features/")
        case = parse(path, errors)
        if case.cid in seen:
            errors.append(f"{path.relative_to(ROOT)}: duplicate case ID {case.cid} (also {seen[case.cid]})")
        seen[case.cid] = path.relative_to(ROOT)
        cases.append(case)
    return cases


ICON = {"todo": "📝 todo", "blocked": "⛔ blocked", "deferred": "⏸ deferred", "n/a": "➖", "retired": "retired"}


def cell(case: Case, platform: str) -> str:
    status = case.status.get(platform)
    if status is None or status == "n/a":
        return "➖"
    last = case.latest(platform)
    if last:
        date, result = last
        return f"✅ PASS {date}" if result == "PASS" else f"❌ FAIL {date}"
    return ICON.get(status, "⏳ not run")


def summary(cases: list[Case], platform: str) -> str:
    counts = {"passed": 0, "failed": 0, "to run": 0, "todo": 0, "blocked": 0, "deferred": 0}
    for case in cases:
        status = case.status.get(platform)
        if status in (None, "n/a", "retired"):
            continue
        last = case.latest(platform)
        if last:
            counts["passed" if last[1] == "PASS" else "failed"] += 1
        elif status == "ready":
            counts["to run"] += 1
        else:
            counts[status] += 1
    return f"**{platform}:** " + " · ".join(f"{n} {label}" for label, n in counts.items())


def render(cases: list[Case]) -> str:
    out = [INDEX_START, ""]
    out += [summary(cases, p) + "  " for p in PLATFORMS]
    for feature in sorted({c.feature for c in cases}):
        out += ["", f"### {feature}", "", "| ID | Case | Rules | " + " | ".join(PLATFORMS) + " |",
                "|---|---|---|" + "---|" * len(PLATFORMS)]
        for case in sorted((c for c in cases if c.feature == feature), key=lambda c: c.cid):
            link = f"[{case.cid}]({case.path.relative_to(DT_DIR).as_posix()})"
            cells = " | ".join(cell(case, p) for p in PLATFORMS)
            out.append(f"| {link} | {case.title} | {case.rules} | {cells} |")
    out += ["", INDEX_END]
    return "\n".join(out)


def current_index() -> str | None:
    text = README.read_text() if README.exists() else ""
    if INDEX_START not in text or INDEX_END not in text:
        return None
    start = text.index(INDEX_START)
    return text[start:text.index(INDEX_END) + len(INDEX_END)]
